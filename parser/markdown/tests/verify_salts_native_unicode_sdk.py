#!/usr/bin/env python3
"""Fail-closed six-RID Unicode 17 ABI/provenance audit of an actual Salts.Native nupkg.

Requires the *published* package version and tag source commit when used for
release admission. A QA-only 2.3.0 package must NOT pass a 2.3.0-rc.17 check.
Does not fetch dependencies or substitute an unpublished SDK. No parser cutover.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
import zipfile

RIDS = (
    "linux-x64", "linux-arm64", "windows-x64",
    "macos-arm64", "android-arm64-v8a", "ios-arm64",
)
SYMBOLS = ("salts_unicode_is_punctuation_or_symbol", "salts_unicode_case_fold")
SHA = re.compile(r"^[0-9a-f]{40}$")
SHA256 = re.compile(r"^[0-9a-f]{64}$")


class AuditError(Exception):
    pass


def insist(test: bool, why: str) -> None:
    if not test:
        raise AuditError(why)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def fields(data: bytes, name: str) -> dict[str, str]:
    result: dict[str, str] = {}
    for row in data.decode("utf-8-sig").splitlines():
        if not row:
            continue
        insist("=" in row, f"{name}: malformed manifest line")
        key, value = row.split("=", 1)
        insist(key not in result and key and value, f"{name}: duplicate/empty {key}")
        result[key] = value
    return result


def archive_symbols(data: bytes, rid: str, llvm_objdump: str) -> None:
    """Inspect actual defined globals, not just header text or archive bytes."""
    is_macho = rid in ("macos-arm64", "ios-arm64")
    with tempfile.TemporaryDirectory(prefix="salts-unicode-audit-") as work:
        path = Path(work) / "unicode.a"
        insist(len(data) <= 64 * 1024 * 1024, f"{rid}: oversized Unicode archive")
        path.write_bytes(data)
        cmd = ([llvm_objdump, "--syms", str(path)] if is_macho else
               ["nm", "--extern-only", "--defined-only", str(path)])
        try:
            result = subprocess.run(
                cmd, text=True, capture_output=True, timeout=60, check=False
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            raise AuditError(f"{rid}: native symbol tool unavailable/failure: {exc}") from exc
        insist(result.returncode == 0, f"{rid}: symbol inspection failed: {result.stderr[:300]}")
        for symbol in SYMBOLS:
            wanted = f"_{symbol}" if is_macho else symbol
            lines = [
                line for line in result.stdout.splitlines()
                if line.split() and line.split()[-1] == wanted
            ]
            if is_macho:
                valid = [
                    line for line in lines
                    if re.search(r"\bg\s+F\s+__TEXT,__text\s+_", line)
                ]
            else:
                valid = [
                    line for line in lines if re.search(r"\sT\s+", line)
                ]
            insist(len(valid) == 1, f"{rid}: {symbol} requires exactly one defined global function, got {len(valid)}")


def audit(package: Path, version: str, source_sha: str,
          header_sha: str, package_sha: str, llvm_objdump: str) -> dict:
    insist(SHA.fullmatch(source_sha) is not None, "expected source SHA must be exact 40-hex")
    insist(SHA256.fullmatch(header_sha) is not None, "expected header SHA-256 must be exact")
    insist(re.fullmatch(r"2\.3\.0(?:-rc\.[1-9][0-9]*)?", version) is not None,
           "unsupported release/version pattern")
    insist(SHA256.fullmatch(package_sha) is not None, "expected package digest must be exact 64-hex")
    insist(package.is_file(), f"missing NuGet file: {package}")
    insist(sha256(package.read_bytes()) == package_sha, "published package SHA-256 mismatch")
    with zipfile.ZipFile(package) as pkg:
        paths = pkg.namelist()
        insist(len(paths) == len(set(paths)), "NuGet has duplicate entries")
        insist(all(
            not name.startswith("/") and "\\" not in name and
            not any(part in (".", "..") for part in name.split("/"))
            for name in paths
        ), "NuGet has unsafe entry names")
        entries = set(paths)
        manifests = {x for x in entries if x.endswith("/salts-sdk-manifest.txt")}
        expected = {f"sdk/{rid}/salts-sdk-manifest.txt" for rid in RIDS}
        insist(manifests == expected, f"wrong manifest RID set: {sorted(manifests ^ expected)}")
        insist("Salts.Native.nuspec" in entries, "NuGet missing canonical nuspec")
        root = ET.fromstring(pkg.read("Salts.Native.nuspec"))
        # NuGet's nuspec namespace is generated by the packing SDK:
        # QA artifacts used 2010/07; the immutable rc.17 release uses 2011/10.
        # Accept only these documented schema revisions and fail closed on others.
        ns_uri = root.tag.removeprefix("{").split("}", 1)[0]
        insist(root.tag == "{" + ns_uri + "}package" and ns_uri in (
            "http://schemas.microsoft.com/packaging/2010/07/nuspec.xsd",
            "http://schemas.microsoft.com/packaging/2011/10/nuspec.xsd",
        ), "NuGet unexpected nuspec root or XML namespace")
        ns = {"n": ns_uri}
        def value(name: str) -> str | None:
            item = root.find(f"n:metadata/n:{name}", ns)
            return item.text if item is not None else None
        insist(value("id") == "Salts.Native", "NuGet identity mismatch")
        insist(value("version") == version, "NuGet version mismatch")
        source = root.find("n:metadata/n:repository", ns)
        insist(source is not None and source.attrib.get("type") == "git",
               "NuGet missing git provenance")
        insist(source.attrib.get("url") == "https://github.com/qigao/salts",
               "NuGet repository URL mismatch")
        insist(source.attrib.get("commit") == source_sha,
               "NuGet RepositoryCommit differs from the requested immutable tag source")

        revisions: set[str] = set()
        header_hashes: set[str] = set()
        records: dict[str, dict] = {}
        for rid in RIDS:
            prefix = f"sdk/{rid}/"
            manifest_path = prefix + "salts-sdk-manifest.txt"
            manifest = fields(pkg.read(manifest_path), manifest_path)
            for key, wanted in (("commit", source_sha),
                                ("version", version),
                                ("profile", "release"),
                                ("vcpkg_cache_contract", "8")):
                insist(manifest.get(key) == wanted,
                       f"{rid}: manifest {key} is not {wanted}")
            revision = manifest.get("vcpkg_cache_revision", "")
            insist(SHA256.fullmatch(revision) is not None,
                   f"{rid}: missing/pin-invalid vcpkg revision")
            revisions.add(revision)
            public_header = prefix + "include/unicode/salts_unicode.h"
            insist(public_header in entries, f"{rid}: missing Unicode public header")
            h = pkg.read(public_header)
            digest = sha256(h)
            insist(digest == header_sha, f"{rid}: public Unicode header checksum changed")
            header_hashes.add(digest)
            for symbol in SYMBOLS:
                insist(h.count((symbol + "(").encode()) == 1,
                       f"{rid}: public header missing/duplicates {symbol}")
            insist(h.count(b"SALTS_UNICODE_ERR_CAPACITY = -4") == 1,
                   f"{rid}: incorrect Unicode capacity error ABI")
            targets = prefix + "lib/cmake/Salts/SaltsTargets.cmake"
            insist(targets in entries and
                   b"add_library(Salts::Unicode STATIC IMPORTED)" in pkg.read(targets),
                   f"{rid}: missing installed Salts::Unicode export")
            library = (prefix + "lib/salts_unicode.lib" if rid == "windows-x64" else
                       prefix + "lib/libsalts_unicode.a")
            insist(library in entries, f"{rid}: missing Unicode static library")
            archive_symbols(pkg.read(library), rid, llvm_objdump)
            records[rid] = {
                "manifest_source_sha": manifest["commit"],
                "unicode_header_sha256": digest,
                "archive_sha256": sha256(pkg.read(library)),
                "abi": "two real globally defined Unicode 17 functions",
            }
        insist(len(revisions) == 1 and len(header_hashes) == 1,
               "six-RID provenance or ABI drift")
        return {
            "verdict": "PASS: immutable SDK package matches requested release provenance",
            "package_sha256": sha256(package.read_bytes()),
            "version": version,
            "source_sha": source_sha,
            "rids": list(RIDS),
            "unicode_header_sha256": header_sha,
            "vcpkg_cache_revision": next(iter(revisions)),
            "detail": records,
        }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--package", type=Path, required=True)
    parser.add_argument("--version", required=True)
    parser.add_argument("--source-sha", required=True)
    parser.add_argument("--header-sha256", required=True)
    parser.add_argument("--package-sha256", required=True)
    parser.add_argument("--llvm-objdump", default="llvm-objdump")
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    try:
        result = audit(args.package, args.version, args.source_sha,
                       args.header_sha256, args.package_sha256, args.llvm_objdump)
    except (AuditError, ValueError, KeyError, OSError, zipfile.BadZipFile,
            ET.ParseError) as exc:
        print(f"FAIL: Salts.Native Unicode 17 SDK release admission: {exc}",
              file=sys.stderr)
        return 1
    output = json.dumps(result, sort_keys=True, indent=2) + "\n"
    if args.report is not None:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(output, encoding="utf-8")
    print(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
